            <h3>Hvad er GLOBUS?</h3>

            <p>GLOBUS er FDFs internationale projekt i samarbejde med Folkekirkens Nødhjælp. Projektet løber fra 2019 til 2022. GLOBUS tager udgangspunkt i FNs 17 Verdensmål, som blev vedtaget i 2015 og skal være nået i 2030.</p>

            <p>Det vil FDF bidrage til og gøre vores for at præge verden i en bæredygtig retning. Alle målene er vigtige - GLOBUS har dog særligt fokus på mål 12 (Ansvarlig forbrug og produktion), 13 (Klimaindsats) og 15 (Livet på land). GLOBUS handler om at få Verdensmålene ind i FDF og bidrage til ansvarligt forbrug og at vi hjælper med at passe på vores fælles natur og klima.</p>

